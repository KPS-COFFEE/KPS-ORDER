const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('public/ops.js','utf8');
const helper=source.slice(source.indexOf('  function morningOrderAlert('),source.indexOf('  async function refreshMorningOrderAlerts('));
const ctx={tr:(ar,en)=>en};vm.createContext(ctx);vm.runInContext(helper,ctx);
const order={id:'one',brand_id:'kps',branch_id:'b2',service:'delivery',preparation_status:'new',delivery_status:'pending',snapshot:{delivery_period:'morning',branch_no:9}};
const action=(patch={},manager=false)=>ctx.morningOrderAlert({...order,...patch},['b2'],manager)?.key;
