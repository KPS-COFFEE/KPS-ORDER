CREATE TABLE fleet_mission_staff (
 brand_id text NOT NULL REFERENCES brands(id), user_id text NOT NULL REFERENCES users(id),
 profile text NOT NULL, PRIMARY KEY(brand_id,user_id), UNIQUE(brand_id,profile)
);
CREATE TABLE fleet_mission_cars (
 vehicle_id text PRIMARY KEY REFERENCES fleet_vehicles(id), brand_id text NOT NULL REFERENCES brands(id),
 category text NOT NULL, art integer, home_profile text, key_holder text REFERENCES users(id),
 broken_meter boolean NOT NULL DEFAULT false, last_km integer CHECK(last_km>=0)
);
CREATE TABLE fleet_supply_routes (
 brand_id text NOT NULL REFERENCES brands(id), kind text NOT NULL, stops jsonb NOT NULL,
 updated_by text NOT NULL REFERENCES users(id), PRIMARY KEY(brand_id,kind)
);
CREATE TABLE fleet_missions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, brand_id text NOT NULL REFERENCES brands(id),
 vehicle_id text NOT NULL REFERENCES fleet_mission_cars(vehicle_id), employee_id text NOT NULL REFERENCES users(id),
 kind text NOT NULL, destination text NOT NULL, stops jsonb NOT NULL DEFAULT '[]',
 planned_minutes integer NOT NULL CHECK(planned_minutes BETWEEN 1 AND 2880),scheduled_at timestamptz NOT NULL,
 requested_by text NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(),
 approved_by text REFERENCES users(id), approved_at timestamptz, issued_by text REFERENCES users(id),
 issued_at timestamptz, started_at timestamptz, ended_at timestamptz, operating_day date NOT NULL,
 start_km integer, end_km integer, start_fuel integer, end_fuel integer, inspection text, outcome text,
 return_requested_at timestamptz, returned_at timestamptz, returned_by text REFERENCES users(id),
 status text NOT NULL CHECK(status IN ('requested','approved','issued','active','completed','cancelled')),
 parent_id bigint REFERENCES fleet_missions(id)
);
CREATE UNIQUE INDEX fleet_mission_one_car ON fleet_missions(vehicle_id) WHERE status IN ('issued','active') AND parent_id IS NULL;
CREATE UNIQUE INDEX fleet_mission_one_employee ON fleet_missions(employee_id) WHERE status IN ('issued','active') AND parent_id IS NULL;
CREATE UNIQUE INDEX fleet_supervisor_one_task ON fleet_missions(parent_id) WHERE parent_id IS NOT NULL AND status IN ('issued','active');
CREATE INDEX fleet_mission_day ON fleet_missions(brand_id,operating_day,id);
CREATE TABLE fleet_morning_reports (
 brand_id text NOT NULL REFERENCES brands(id), day date NOT NULL, snapshot jsonb NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), mail_id text REFERENCES email_outbox(id), PRIMARY KEY(brand_id,day)
);
