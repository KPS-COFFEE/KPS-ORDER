-- Additive engagement records. No customer, order or financial history is rewritten.
ALTER TABLE orders ADD COLUMN discount_halalas bigint NOT NULL DEFAULT 0 CHECK(discount_halalas>=0);
ALTER TABLE orders DROP CONSTRAINT orders_total_halalas_check;
ALTER TABLE orders ADD CONSTRAINT orders_total_halalas_check CHECK(discount_halalas<=subtotal_halalas AND total_halalas=subtotal_halalas-discount_halalas+delivery_fee_halalas);
CREATE UNIQUE INDEX engagement_users_brand_id ON users(brand_id,id);
CREATE TABLE customer_followups (
 id text PRIMARY KEY, brand_id text NOT NULL REFERENCES brands(id), customer_id text NOT NULL,
 actor_id text NOT NULL REFERENCES users(id), status text NOT NULL CHECK(status IN ('open','resolved')),
 note text NOT NULL CHECK(length(note) BETWEEN 1 AND 2000), next_followup_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(brand_id,customer_id) REFERENCES users(brand_id,id)
);
CREATE INDEX customer_followups_scope ON customer_followups(brand_id,customer_id,created_at,id);
CREATE INDEX customer_followups_page ON customer_followups(brand_id,customer_id,id);
CREATE TABLE customer_marketing_notices (
 id text PRIMARY KEY,brand_id text NOT NULL REFERENCES brands(id),version text NOT NULL,
 text_ar text NOT NULL CHECK(length(text_ar) BETWEEN 1 AND 5000),text_en text NOT NULL CHECK(length(text_en) BETWEEN 1 AND 5000),
 actor_id text NOT NULL REFERENCES users(id),created_at timestamptz NOT NULL DEFAULT now(),UNIQUE(brand_id,version)
);
CREATE TABLE customer_marketing_consents (
 seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id text PRIMARY KEY, brand_id text NOT NULL REFERENCES brands(id), customer_id text NOT NULL,
 channel text NOT NULL CHECK(channel IN ('sms','whatsapp')), granted boolean NOT NULL,
 notice_version text NOT NULL CHECK(length(notice_version) BETWEEN 1 AND 100),
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(brand_id,customer_id) REFERENCES users(brand_id,id)
);
CREATE INDEX customer_consents_scope ON customer_marketing_consents(brand_id,customer_id,channel,created_at,id);
CREATE TABLE benefit_programs (
 id text PRIMARY KEY, brand_id text NOT NULL REFERENCES brands(id), actor_id text NOT NULL REFERENCES users(id),
 definition jsonb NOT NULL CHECK(jsonb_typeof(definition)='object'), created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(brand_id,id)
);
CREATE TABLE benefit_rules (
 id text PRIMARY KEY, brand_id text NOT NULL REFERENCES brands(id), code text NOT NULL,
 definition jsonb NOT NULL CHECK(jsonb_typeof(definition)='object'), active boolean NOT NULL DEFAULT false,
 actor_id text NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(brand_id,id), UNIQUE(brand_id,code)
);
CREATE TABLE customer_wallets (
 brand_id text NOT NULL, customer_id text NOT NULL, balance_halalas bigint NOT NULL DEFAULT 0,
 PRIMARY KEY(brand_id,customer_id), FOREIGN KEY(brand_id,customer_id) REFERENCES users(brand_id,id)
);
CREATE TABLE benefit_order_states (
 order_id text PRIMARY KEY REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
 brand_id text NOT NULL, customer_id text NOT NULL, rule_id text,
 discount_halalas bigint NOT NULL CHECK(discount_halalas>=0),
 redeemed_halalas bigint NOT NULL CHECK(redeemed_halalas>=0), earn_bps integer NOT NULL CHECK(earn_bps BETWEEN 0 AND 10000),
 earn_base_halalas bigint NOT NULL CHECK(earn_base_halalas>=0), earned_halalas bigint NOT NULL DEFAULT 0,
 returned_halalas bigint NOT NULL DEFAULT 0, revision bigint NOT NULL DEFAULT 0,
 FOREIGN KEY(brand_id,customer_id) REFERENCES users(brand_id,id),
 FOREIGN KEY(brand_id,rule_id) REFERENCES benefit_rules(brand_id,id),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX benefit_usage_scope ON benefit_order_states(brand_id,customer_id,rule_id);
CREATE INDEX benefit_rule_usage ON benefit_order_states(brand_id,rule_id,customer_id);
CREATE TABLE customer_wallet_entries (
 id text PRIMARY KEY, brand_id text NOT NULL, customer_id text NOT NULL, order_id text NOT NULL,
 amount_halalas bigint NOT NULL CHECK(amount_halalas<>0),
 kind text NOT NULL CHECK(kind IN ('earn','earn_reversal','redemption','redemption_return')),
 source_key text NOT NULL UNIQUE, created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(brand_id,customer_id) REFERENCES customer_wallets(brand_id,customer_id),
 FOREIGN KEY(order_id) REFERENCES benefit_order_states(order_id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX customer_wallet_history ON customer_wallet_entries(brand_id,customer_id,id);
-- Append-only decisions/ledgers. State projections alone may be updated.
CREATE FUNCTION engagement_immutable() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'Engagement history is append-only'; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER immutable_followup BEFORE UPDATE OR DELETE ON customer_followups FOR EACH ROW EXECUTE FUNCTION engagement_immutable();
CREATE TRIGGER immutable_consent BEFORE UPDATE OR DELETE ON customer_marketing_consents FOR EACH ROW EXECUTE FUNCTION engagement_immutable();
CREATE TRIGGER immutable_notice BEFORE UPDATE OR DELETE ON customer_marketing_notices FOR EACH ROW EXECUTE FUNCTION engagement_immutable();
CREATE TRIGGER immutable_program BEFORE UPDATE OR DELETE ON benefit_programs FOR EACH ROW EXECUTE FUNCTION engagement_immutable();
CREATE TRIGGER immutable_wallet_entry BEFORE UPDATE OR DELETE ON customer_wallet_entries FOR EACH ROW EXECUTE FUNCTION engagement_immutable();
CREATE FUNCTION engagement_rule_immutable() RETURNS trigger AS $$
BEGIN
 IF TG_OP='DELETE' OR NEW.id IS DISTINCT FROM OLD.id OR NEW.brand_id IS DISTINCT FROM OLD.brand_id
 OR NEW.code IS DISTINCT FROM OLD.code OR NEW.definition IS DISTINCT FROM OLD.definition
 OR NEW.actor_id IS DISTINCT FROM OLD.actor_id OR NEW.created_at IS DISTINCT FROM OLD.created_at
 THEN RAISE EXCEPTION 'Create a new benefit rule version'; END IF;
 RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER immutable_rule BEFORE UPDATE OR DELETE ON benefit_rules FOR EACH ROW EXECUTE FUNCTION engagement_rule_immutable();
CREATE FUNCTION engagement_wallet_entry() RETURNS trigger AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM benefit_order_states s WHERE s.order_id=NEW.order_id
  AND s.brand_id=NEW.brand_id AND s.customer_id=NEW.customer_id)
 THEN RAISE EXCEPTION 'Wallet order scope mismatch'; END IF;
 UPDATE customer_wallets SET balance_halalas=balance_halalas+NEW.amount_halalas
 WHERE brand_id=NEW.brand_id AND customer_id=NEW.customer_id;
 RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER wallet_entry_balance AFTER INSERT ON customer_wallet_entries FOR EACH ROW EXECUTE FUNCTION engagement_wallet_entry();

-- Convergent, transaction-end projections. Confirmed receipts/refunds only.
-- A clawback may leave a negative balance after previous rewards were spent;
-- that debt blocks further redemption instead of silently forgiving it.
CREATE FUNCTION sync_order_benefits(p_order text) RETURNS void AS $$
DECLARE s benefit_order_states%ROWTYPE; o orders%ROWTYPE; net bigint; paid bigint;
 earned bigint:=0; returned bigint:=0; delta bigint;
BEGIN
 SELECT * INTO s FROM benefit_order_states WHERE order_id=p_order;
 IF NOT FOUND THEN RETURN; END IF;
 SELECT * INTO o FROM orders WHERE id=p_order FOR UPDATE;
 IF NOT FOUND OR o.brand_id<>s.brand_id OR o.customer_id<>s.customer_id THEN
  RAISE EXCEPTION 'Benefit order ownership mismatch';
 END IF;
 PERFORM 1 FROM customer_wallets WHERE brand_id=s.brand_id AND customer_id=s.customer_id FOR UPDATE;
 SELECT * INTO s FROM benefit_order_states WHERE order_id=p_order FOR UPDATE;
 SELECT COALESCE(sum(amount_halalas),0) INTO paid FROM (
  SELECT amount_halalas FROM collections WHERE order_id=p_order
  UNION ALL SELECT amount_halalas FROM branch_online_receipts WHERE order_id=p_order AND disposition='applied' AND mode='live'
 ) x;
 SELECT paid-COALESCE(sum(amount_halalas),0) INTO net FROM (
  SELECT amount_halalas FROM refunds WHERE order_id=p_order
  UNION ALL SELECT amount_halalas FROM branch_online_refunds WHERE order_id=p_order AND status='verified'
 ) x;
 net:=greatest(0,least(o.total_halalas,net));
 IF o.preparation_status NOT IN ('cancelled','rejected') AND o.delivery_status NOT IN ('cancelled','rejected')
 AND (o.preparation_status='completed' OR o.delivery_status='delivered') AND o.total_halalas>0
 AND COALESCE(o.snapshot->>'branch_payment_mode','')<>'test' AND paid>=o.total_halalas THEN
  earned:=floor(s.earn_base_halalas::numeric*s.earn_bps*net/(10000::numeric*o.total_halalas));
 END IF;
 IF o.preparation_status IN ('cancelled','rejected') OR o.delivery_status='cancelled' THEN
  returned:=s.redeemed_halalas;
 ELSIF paid>=o.total_halalas AND o.total_halalas>0 THEN
  returned:=floor(s.redeemed_halalas::numeric*(o.total_halalas-net)/o.total_halalas);
 END IF;
 IF earned<>s.earned_halalas OR returned<>s.returned_halalas THEN
  delta:=earned-s.earned_halalas;
  IF delta<>0 THEN
   INSERT INTO customer_wallet_entries(id,brand_id,customer_id,order_id,amount_halalas,kind,source_key)
   VALUES('wallet_'||gen_random_uuid(),s.brand_id,s.customer_id,p_order,delta,
    CASE WHEN delta>0 THEN 'earn' ELSE 'earn_reversal' END,p_order||':earn:'||(s.revision+1));
  END IF;
  delta:=returned-s.returned_halalas;
  IF delta<>0 THEN
   INSERT INTO customer_wallet_entries(id,brand_id,customer_id,order_id,amount_halalas,kind,source_key)
   VALUES('wallet_'||gen_random_uuid(),s.brand_id,s.customer_id,p_order,delta,'redemption_return',p_order||':return:'||(s.revision+1));
  END IF;
  UPDATE benefit_order_states SET earned_halalas=earned,returned_halalas=returned,revision=revision+1 WHERE order_id=p_order;
 END IF;
END; $$ LANGUAGE plpgsql;
CREATE FUNCTION sync_benefit_event() RETURNS trigger AS $$
BEGIN
 IF TG_TABLE_NAME='orders' THEN PERFORM sync_order_benefits(NEW.id);
 ELSE PERFORM sync_order_benefits(NEW.order_id); END IF;
 RETURN NULL;
END; $$ LANGUAGE plpgsql;
CREATE CONSTRAINT TRIGGER order_benefit_sync AFTER INSERT OR UPDATE ON orders DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sync_benefit_event();
CREATE CONSTRAINT TRIGGER collection_benefit_sync AFTER INSERT ON collections DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sync_benefit_event();
CREATE CONSTRAINT TRIGGER refund_benefit_sync AFTER INSERT ON refunds DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sync_benefit_event();
CREATE CONSTRAINT TRIGGER online_receipt_benefit_sync AFTER INSERT OR UPDATE ON branch_online_receipts DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sync_benefit_event();
CREATE CONSTRAINT TRIGGER online_refund_benefit_sync AFTER INSERT OR UPDATE ON branch_online_refunds DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sync_benefit_event();
